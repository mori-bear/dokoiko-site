def build_travel_time(hub_key, hub_tt, extras):
    """hub都市からのtravelTimeと、各主要都市→hub→目的地で計算"""
    tt = {}
    # hub itself
    if hub_key:
        tt[hub_key] = hub_tt
    # 各都市→hub→目的地
    if hub_key in CITY_TO_HUB:
        for city, city_to_hub in CITY_TO_HUB[hub_key].items():
            tt[city] = city_to_hub + hub_tt
    # 上書き or 追加
    for city, val in extras.items():
        tt[city] = val
    return tt

