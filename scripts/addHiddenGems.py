existing_ids = {d['id'] for d in data}
existing_names = {d['name'] for d in data}

added = []
skipped = []

for entry in ADDS:
    iid, name, pref, region, hub_key, hub_name, hub_tt, stay, spots, desc, lat, lng, tags, hotel_kw = entry[:14]
    extras = entry[14] if len(entry) > 14 else None
    if iid in existing_ids:
        skipped.append(f'{name} (id重複: {iid})')
        continue
    if name in existing_names:
        skipped.append(f'{name} (同名既存)')
        continue
    tt = make_tt(hub_key, hub_tt, extras)
    new_dest = {
        'id': iid, 'name': name, 'type': 'destination',
        'region': region, 'prefecture': pref,
        'hub': hub_name, 'hubName': hub_name, 'hubCity': hub_name,
        'stayAllowed': stay, 'departures': [hub_name], 'weight': 1.0,
        'description': desc, 'tags': tags,
        'spots': [{'name': s} for s in spots],
        'shinkansenAccess': False, 'requiresCar': False, 'isIsland': False,
        'destType': 'sight', 'hotelSearch': hotel_kw,
        'lat': lat, 'lng': lng, 'travelTime': tt,
        'stayRecommendation': stay[0] if stay else 'daytrip',
        'gateways': {'rail': [], 'airport': [], 'bus': [], 'ferry': []},
        'hotelLinks': {'rakuten': rakuten(hotel_kw), 'jalan': jalan(hotel_kw)},
        'rentalCarRecommended': any(t in tags for t in ['自然','絶景','秘境','山','高原']),
    }
    data.append(new_dest)
    added.append((name, pref, hub_name))

DEST.write_text(json.dumps(data, ensure_ascii=False, indent=2))

